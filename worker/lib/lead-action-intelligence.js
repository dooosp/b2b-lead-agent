import { toLeadBriefV1 } from './leadbrief-v1.js';

const DEFAULT_STALE_AFTER_DAYS = 90;

const ACTION_LABELS = Object.freeze({
  prepare_human_follow_up: 'Prepare reviewed follow-up',
  decide_review_status: 'Decide review status',
  verify_evidence: 'Verify evidence first',
  resolve_data_gaps: 'Resolve data gaps',
  enrich_before_review: 'Enrich before review',
  refresh_signal: 'Refresh stale signal',
  reconcile_review_conflict: 'Reconcile review conflict',
  schedule_recheck: 'Schedule recheck',
  keep_out_of_queue: 'Keep out of active queue',
  review_lead: 'Review lead',
});

const RISK_LABELS = Object.freeze({
  human_review_pending: 'Human review is still pending',
  rejected_review: 'Lead was rejected by human review',
  deferred_review: 'Lead is deferred',
  missing_evidence: 'Published source or direct evidence is missing',
  verified_without_evidence: 'Lead is verified without complete evidence',
  data_gaps: 'Open data gaps remain',
  low_confidence: 'Confidence is low',
  unverified: 'Verification is not complete',
  non_llm_generation: 'Lead was not generated by the normal LLM path',
  stale_signal: 'Source signal may be stale',
  approved_but_unverified: 'Approved review state conflicts with verification',
  approved_with_review_risks: 'Approved review state still has evidence or data risks',
  conflicting_evidence: 'Conflicting evidence needs resolution',
});

function cleanText(value, fallback = '') {
  const text = String(value ?? '').replace(/\s+/g, ' ').trim();
  return text || fallback;
}

function normalizeStringArray(value) {
  return (Array.isArray(value) ? value : [])
    .map((item) => cleanText(item))
    .filter(Boolean);
}

function addUnique(items, value) {
  const text = cleanText(value);
  if (text && !items.includes(text)) items.push(text);
}

function addRisk(risks, code, severity = 'medium', detail = '') {
  if (!code || risks.some((risk) => risk.code === code)) return;
  risks.push({
    code,
    label: RISK_LABELS[code] || code,
    severity,
    ...(cleanText(detail) ? { detail: cleanText(detail) } : {}),
  });
}

function pickText(record, keys, fallback = '') {
  for (const key of keys) {
    const text = cleanText(record && record[key]);
    if (text) return text;
  }
  return fallback;
}

function pickArray(record, keys) {
  for (const key of keys) {
    const items = normalizeStringArray(record && record[key]);
    if (items.length > 0) return items;
  }
  return [];
}

function normalizeEvidenceItems(value) {
  return (Array.isArray(value) ? value : [])
    .map((item) => {
      if (!item || typeof item !== 'object') return null;
      const quote = cleanText(item.quote);
      if (!quote) return null;
      return {
        field: cleanText(item.field, 'evidence'),
        quote,
        sourceUrl: cleanText(item.sourceUrl || item.source_url),
        contradicts: cleanText(item.contradicts || item.conflictsWith || item.conflict),
      };
    })
    .filter(Boolean);
}

function normalizeSources(value) {
  return (Array.isArray(value) ? value : [])
    .map((source) => {
      if (!source || typeof source !== 'object') return null;
      const title = cleanText(source.title);
      const url = cleanText(source.url);
      if (!title && !url) return null;
      return {
        ...source,
        title: title || url,
        url,
      };
    })
    .filter(Boolean);
}

function parseSourceDate(source) {
  const raw = cleanText(
    source?.publishedAt
      || source?.published_at
      || source?.publishedDate
      || source?.published_date
      || source?.date
  );
  if (!raw) return null;
  const parsed = new Date(raw);
  return Number.isNaN(parsed.getTime()) ? null : parsed;
}

function staleSources(sources, now, staleAfterDays) {
  const nowDate = now instanceof Date ? now : new Date(now || Date.now());
  if (Number.isNaN(nowDate.getTime())) return [];
  const thresholdMs = staleAfterDays * 24 * 60 * 60 * 1000;
  return sources.filter((source) => {
    const published = parseSourceDate(source);
    return published && nowDate.getTime() - published.getTime() > thresholdMs;
  });
}

function collectConflictFields(lead, evidence) {
  const fields = [];
  const conflicts = Array.isArray(lead.conflicts) ? lead.conflicts : [];
  for (const conflict of conflicts) {
    if (typeof conflict === 'string') {
      addUnique(fields, conflict);
    } else if (conflict && typeof conflict === 'object') {
      addUnique(fields, conflict.field || conflict.topic || conflict.reason);
    }
  }
  for (const item of evidence) {
    addUnique(fields, item.contradicts);
  }
  return fields;
}

function chooseStakeholderAngle({ brief, evidence, dataGaps }) {
  const buyerRole = pickText(brief, ['buyerRole', 'buyer_role'], 'stakeholder owner');
  const product = pickText(brief, ['product', 'recommendedProduct', 'recommended_product', 'productName'], 'recommended solution');
  const signal = cleanText(brief.signal || brief.summary, 'the public buying signal');
  const painPoints = pickArray(brief, ['painPoints', 'pain_points']);
  const buyingSignals = pickArray(brief, ['buyingSignals', 'buying_signals']);
  const proof = evidence.length > 0 ? `proof quote "${evidence[0].quote}"` : 'source proof that still needs confirmation';
  const context = painPoints[0] || buyingSignals[0] || signal;
  const caveat = dataGaps.length > 0 ? ' Resolve missing info before using this angle.' : '';
  return `${buyerRole}: connect ${product} to ${context} using ${proof}.${caveat}`;
}

function chooseSuggestedFollowUp({ brief, evidence, dataGaps }) {
  const company = cleanText(brief.company, 'the account');
  const product = pickText(brief, ['product', 'recommendedProduct', 'recommended_product', 'productName'], 'the relevant solution');
  const signal = cleanText(brief.signal || brief.summary, 'the public signal');
  const recommended = cleanText(brief.recommendedMessage || brief.salesPitch || brief.sales_pitch);
  const proof = evidence.length > 0 ? ` I saw the public signal: "${evidence[0].quote}."` : '';
  const ask = recommended
    ? `${recommended} Context anchor: ${product} for ${signal}.`
    : `Would it be useful to compare ${product} against ${signal}?`;
  const caveat = dataGaps.length > 0
    ? ' Keep this as an internal draft until the listed gaps are resolved.'
    : ' Personalize and send only after human approval.';
  return `Human-review draft for ${company}: ${ask}${proof} ${caveat}`;
}

function priorityFor({ action, reviewStatus, hasConflicts }) {
  if (action === 'keep_out_of_queue') return 'blocked';
  if (action === 'schedule_recheck') return 'hold';
  if (action === 'prepare_human_follow_up' || action === 'decide_review_status') return 'high';
  if (action === 'reconcile_review_conflict') return 'high';
  if (reviewStatus === 'APPROVED' && hasConflicts) return 'high';
  return 'medium';
}

function confidenceFor({ action, risks, reviewStatus, verificationStatus, confidence }) {
  if (action === 'prepare_human_follow_up' && risks.length === 0 && confidence === 'HIGH') return 'high';
  if (action === 'decide_review_status' && verificationStatus === 'verified') return 'medium';
  if (reviewStatus === 'REJECTED' || action === 'schedule_recheck') return 'medium';
  if (risks.some((risk) => risk.severity === 'high')) return 'low';
  if (confidence === 'LOW') return 'low';
  return risks.length === 0 ? 'medium' : 'low';
}

function reasonFor(action, context) {
  const {
    reviewStatus,
    verificationStatus,
    confidence,
    evidenceCount,
    sourceCount,
    dataGapCount,
    staleCount,
    conflictFields,
  } = context;
  const base = `reviewStatus=${reviewStatus}, verificationStatus=${verificationStatus}, confidence=${confidence}, evidence=${evidenceCount}, sources=${sourceCount}, dataGaps=${dataGapCount}.`;

  if (action === 'prepare_human_follow_up') {
    return `Lead is approved, verified, high-confidence, and evidence-backed with no open data gaps. ${base}`;
  }
  if (action === 'decide_review_status') {
    return `Verified evidence is present and no data gaps remain, but human review status is not final. ${base}`;
  }
  if (action === 'verify_evidence') {
    return `Evidence is incomplete or verification is overstated, so reviewer should verify source support first. ${base}`;
  }
  if (action === 'resolve_data_gaps') {
    return `Open data gaps remain and should be resolved before outreach or approval. ${base}`;
  }
  if (action === 'enrich_before_review') {
    return `Low-confidence or non-LLM generation needs more evidence before a review decision. ${base}`;
  }
  if (action === 'refresh_signal') {
    return `At least ${staleCount} source signal is older than the freshness threshold and needs revalidation. ${base}`;
  }
  if (action === 'reconcile_review_conflict') {
    return `Approved review state conflicts with verification or evidence state; resolve ${conflictFields.join(', ') || 'the conflict'} before follow-up. ${base}`;
  }
  if (action === 'schedule_recheck') {
    return `Lead is deferred; define the recheck condition before it returns to active review. ${base}`;
  }
  if (action === 'keep_out_of_queue') {
    return `Lead was rejected by human review and should stay out of active follow-up until new evidence appears. ${base}`;
  }
  return `Reviewer should inspect the LeadBrief and decide the next human review step. ${base}`;
}

function chooseAction(context) {
  const {
    reviewStatus,
    verificationStatus,
    generationMode,
    confidence,
    evidenceCount,
    sourceCount,
    dataGapCount,
    staleCount,
    hasConflicts,
  } = context;
  const missingEvidence = evidenceCount === 0 || sourceCount === 0;

  if (reviewStatus === 'REJECTED') return 'keep_out_of_queue';
  if (
    reviewStatus === 'APPROVED'
    && (verificationStatus !== 'verified' || hasConflicts || missingEvidence || dataGapCount > 0 || confidence === 'LOW')
  ) {
    return 'reconcile_review_conflict';
  }
  if (staleCount > 0) return 'refresh_signal';
  if (confidence === 'LOW' || generationMode === 'heuristic' || generationMode === 'unavailable') return 'enrich_before_review';
  if (missingEvidence) return 'verify_evidence';
  if (dataGapCount > 0) return 'resolve_data_gaps';
  if (reviewStatus === 'DEFERRED') return 'schedule_recheck';
  if (reviewStatus === 'APPROVED' && verificationStatus === 'verified') return 'prepare_human_follow_up';
  if (verificationStatus === 'verified') return 'decide_review_status';
  return 'review_lead';
}

export function buildLeadActionIntelligence(lead = {}, options = {}) {
  const brief = toLeadBriefV1(lead);
  const reviewStatus = brief.reviewStatus;
  const verificationStatus = brief.verificationStatus;
  const generationMode = brief.generationMode;
  const confidence = brief.confidence;
  const evidence = normalizeEvidenceItems(brief.evidence);
  const sources = normalizeSources(brief.sources);
  const dataGaps = normalizeStringArray(brief.dataGaps);
  const staleAfterDays = Number.isFinite(Number(options.staleAfterDays))
    ? Number(options.staleAfterDays)
    : DEFAULT_STALE_AFTER_DAYS;
  const stale = staleSources(sources, options.now, staleAfterDays);
  const conflictFields = collectConflictFields(lead, evidence);
  const hasConflicts = conflictFields.length > 0;
  const missingEvidence = evidence.length === 0 || sources.length === 0;
  const risks = [];

  if (reviewStatus === 'NEEDS_REVIEW' || reviewStatus === 'NEW') addRisk(risks, 'human_review_pending', 'medium');
  if (reviewStatus === 'REJECTED') addRisk(risks, 'rejected_review', 'high');
  if (reviewStatus === 'DEFERRED') addRisk(risks, 'deferred_review', 'medium');
  if (missingEvidence) addRisk(risks, 'missing_evidence', 'high');
  if (verificationStatus === 'verified' && missingEvidence) addRisk(risks, 'verified_without_evidence', 'high');
  if (dataGaps.length > 0) addRisk(risks, 'data_gaps', 'medium', `${dataGaps.length} gap(s)`);
  if (confidence === 'LOW') addRisk(risks, 'low_confidence', 'medium');
  if (verificationStatus !== 'verified') addRisk(risks, 'unverified', 'medium');
  if (generationMode !== 'llm') addRisk(risks, 'non_llm_generation', 'medium', generationMode);
  if (stale.length > 0) addRisk(risks, 'stale_signal', 'medium', `${stale.length} stale source(s)`);
  if (reviewStatus === 'APPROVED' && verificationStatus !== 'verified') addRisk(risks, 'approved_but_unverified', 'high');
  if (reviewStatus === 'APPROVED' && (missingEvidence || dataGaps.length > 0 || confidence === 'LOW' || stale.length > 0)) {
    addRisk(risks, 'approved_with_review_risks', 'high');
  }
  if (hasConflicts) addRisk(risks, 'conflicting_evidence', 'high', conflictFields.join(', '));

  const context = {
    reviewStatus,
    verificationStatus,
    generationMode,
    confidence,
    evidenceCount: evidence.length,
    sourceCount: sources.length,
    dataGapCount: dataGaps.length,
    staleCount: stale.length,
    conflictFields,
    hasConflicts,
  };
  const nextReviewAction = chooseAction(context);
  const missingInfoPrompts = [];

  for (const gap of dataGaps.slice(0, 4)) addUnique(missingInfoPrompts, `Resolve data gap: ${gap}`);
  if (sources.length === 0) addUnique(missingInfoPrompts, 'Add at least one published source URL.');
  if (evidence.length === 0) addUnique(missingInfoPrompts, 'Add a direct evidence quote tied to a source URL.');
  if (verificationStatus !== 'verified') addUnique(missingInfoPrompts, 'Confirm verification status before approval.');
  if (confidence === 'LOW') addUnique(missingInfoPrompts, 'Add or refresh evidence before raising confidence.');
  if (stale.length > 0) addUnique(missingInfoPrompts, 'Refresh stale public sources or revalidate the signal date.');
  if (hasConflicts) addUnique(missingInfoPrompts, `Resolve conflicting evidence: ${conflictFields.join(', ') || 'conflict'}.`);

  return {
    nextReviewAction,
    nextReviewActionLabel: ACTION_LABELS[nextReviewAction] || ACTION_LABELS.review_lead,
    nextReviewActionReason: reasonFor(nextReviewAction, context),
    riskFlags: risks,
    missingInfoPrompts,
    stakeholderAngle: chooseStakeholderAngle({ brief, evidence, dataGaps }),
    suggestedFollowUp: chooseSuggestedFollowUp({ brief, evidence, dataGaps }),
    reviewPriority: priorityFor({ action: nextReviewAction, reviewStatus, hasConflicts }),
    actionConfidence: confidenceFor({
      action: nextReviewAction,
      risks,
      reviewStatus,
      verificationStatus,
      confidence,
    }),
  };
}
